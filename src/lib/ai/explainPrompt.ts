import type { ExplainFacts } from './explainFacts'

export const SYSTEM_PROMPT = `あなたは、小水力発電の水車選定ツールの「解説担当」です。
読者は、水力の専門家ではない人（自治体の担当者など）です。ツールが計算した結果を、やさしい日本語で説明してください。

# 守ること
- 数値は、渡された「事実（FACTS）」に書かれているものだけを使う。FACTS にない数値を作らない。自分で計算して新しい数値を出さない。
- 数値には単位を付け、「目安」「約」などの断定を避ける表現にする。
- 数値の後ろに、出どころを［計算結果］［亀の甲 図4.3-8］［判定］のように付ける。マニュアルの図番は、FACTS の「出典」の記載に合わせる。
- 専門用語は、初めて出るときに、かっこ書きで一言説明する。
- 製品の適合、性能や効率の保証、法規・補助金・水利権の判断は、断定しない。「メーカーや専門家に確認が必要」と書く。
- 判定が NG、注意、INFO の項目は、その意味と、対処の方向（一般的な考え方）を書く。具体的な数値の提案はしない。
- FACTS に「マニュアル選定」があるときは、採用する値は、亀の甲で選ばれた枠であることを明確にする。
  計算の結果が違う枠になっているときは、「効率を優先した参考値で、低速・大径になりやすいこと」と「マニュアルは標準品の枠から選ぶこと」を、やさしく説明する。
  亀の甲が「適用外」のときは、図の範囲外であり、計算結果は参考値にとどまることを説明する。

# 書き方
次の4つの見出しで、Markdown で書く。全体で 700 字以内。
## 一言でいうと
## 結果の読み方
## 注意が必要な点
## 次にやること
各見出しは、2〜5 行の短い文か、箇条書きにする。最後に、「概略の検討用です。詳細は、製造者や専門家にご確認ください。」と1行書く。`

export function buildUserMessage(facts: ExplainFacts): string {
  return `次の FACTS だけを根拠にして、結果を説明してください。

\`\`\`json
${JSON.stringify(facts, null, 2)}
\`\`\``
}

/** AI を使えないとき（キー未設定のデモなど）の、簡易な解説。事実から機械的に文章を作る */
export function mockExplain(facts: ExplainFacts): string {
  const r = facts.計算結果, k = facts.マニュアル選定 as Record<string, unknown> | undefined
  const frame = k?.選ばれた枠 as { 枠番: string; 回転速度_rpm: number; ランナ出口径_mm: number } | null | undefined
  const ng = facts.判定.filter(j => j.結果 === 'NG' || j.結果 === '注意')
  const lines: string[] = []
  lines.push('## 一言でいうと')
  lines.push(`有効落差 ${facts.条件.有効落差_m} m・流量 ${facts.条件.設計流量_m3s} m³/s の条件では、${r.水車の種類}で、水車出力は約 ${r.水車出力_kW} kW、年間発電量は約 ${r.年間発電量_MWh} MWh が目安です。［計算結果］`)
  lines.push('')
  lines.push('## 結果の読み方')
  lines.push(`- 定格回転速度は ${r.定格回転速度_rpm} rpm（${r.極数} 極）、比速度は約 ${r.比速度Ns} です。［計算結果］`)
  if (frame) lines.push(`- マニュアルの選定図（亀の甲）では、${frame.枠番}（${frame.回転速度_rpm} rpm、ランナ出口径 ${frame.ランナ出口径_mm} mm）の枠に入ります。これが採用の目安です。［亀の甲］`)
  else if (k) lines.push('- マニュアルの選定図（亀の甲）では、図の範囲外のため、計算結果は参考値にとどまります。［亀の甲］')
  lines.push('')
  lines.push('## 注意が必要な点')
  if (ng.length) ng.forEach(j => lines.push(`- ${j.項目}：${j.結果}（${j.内容}）［判定］`))
  else lines.push('- 計算上の判定で、特に注意が必要な項目はありませんでした。［判定］')
  lines.push('')
  lines.push('## 次にやること')
  lines.push('- 流量と落差の実測（季節ごとの変化）を確認する。')
  lines.push('- 候補の機種について、製造者に条件を伝えて相談する。')
  lines.push('')
  lines.push('概略の検討用です。詳細は、製造者や専門家にご確認ください。')
  return lines.join('\n')
}
